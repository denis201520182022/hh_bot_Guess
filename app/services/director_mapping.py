def extract_bracket_content(job_title: str) -> Optional[str]:
    """
    Извлекает текст в скобках из названия вакансии.

    Args:
        job_title: название вакансии (например "Продавец-консультант GUESS (ТЦ Екатеринбург АУТЛЕТ)")

    Returns:
        Текст в скобках или None (например "ТЦ Екатеринбург АУТЛЕТ")
    """
    if not job_title:
        return None

    match = re.search(r'\(([^)]+)\)', job_title)
    if match:
        return match.group(1).strip()
    return None


def resolve_director_name(job_title: str, city: Optional[str] = None) -> Optional[str]:
    """
    Определяет имя директора по названию вакансии и городу.
    Извлекает текст в скобках и ищет совпадение в маппинге с учетом города.
    """
    if not job_title:
        return None

    bracket_content = extract_bracket_content(job_title)
    city_lower = city.lower().strip() if city else ""
    
    # 1. Поиск по тексту в скобках + городу
    if bracket_content:
        bracket_lower = bracket_content.lower().strip()
        key = (bracket_lower, city_lower)
        if key in DIRECTOR_TC_MAP:
            return DIRECTOR_TC_MAP[key]

    # 2. Фолбек: поиск ключа ТЦ в названии вакансии при совпадении города
    job_title_lower = job_title.lower()
    for (tc_key, city_key), director_name in DIRECTOR_TC_MAP.items():
        if city_key == city_lower and tc_key in job_title_lower:
            return director_name

    return None

